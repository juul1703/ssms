        "tekst": "Central questions are usually formulated broadly: ‘research into absenteeism’, ‘customer satisfaction research’, ‘research into a company’s internal communication’. The first step is to read up on the topic and to mark off the question areas as well as possible. You also check whether anything has already been published about it, and whether there are models that might offer solutions (see chapters 4 and 5). In short: you collect information. This phase is called [[preliminary research|Preliminary research]].\n\n**Preliminary research is problem analysis.** There is a lot of confusion about the term ‘preliminary research’. When is there preliminary research, and is it necessary? When does it end and the main research begin? Preliminary research obviously takes place before the main research. How do you do it?\n- You look for **background information** about your topic.\n- You look for **literature** about previously presented research results.\n- You collect material by **talking to a few people**.\n\nIn short, you immerse yourself in the topic and mark it off. Preliminary research is therefore also called [[problem analysis|Problem analysis]]. Sometimes, during the problem analysis, it turns out that the problem (and the reason for it) is somewhat different from what was first thought. That is not a disaster: the problem can still be clearly defined during the problem analysis.\n\n**Where do you look for information?** Information is collected throughout the whole research project: as part of your preliminary research when you do a literature review, and always during the second phase of your research. The first place to look is the **client’s archive or documentation centre**. There you find documents that clarify the reason for the research, such as **minutes of meetings, financial overviews, organisation charts and policy plans**."
